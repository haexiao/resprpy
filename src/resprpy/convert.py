def convert_MR(x, from_=None, to=None, S=None, t=None, P=None, quiet=False):
    """Convert metabolic rates between rate-unit strings, e.g.
    convert_MR(0.001, from_='mg/sec', to='umol/min/g', S=35, t=20).

    Mirrors respR::convert_MR. Accepts plain rates or a convert_rate result
    (then 'from' is extracted automatically)."""
    obj = hasattr(x, "rate_output") and hasattr(x, "summary")
    if obj:
        rate = np.asarray(x.rate_output, dtype=float)
        S = x.inputs.get("S") if S is None else S
        t = x.inputs.get("t") if t is None else t
        P = x.inputs.get("P") if P is None else P
        from_ = x.output_unit
    else:
        rate = _asnum(x)
    if to is None:
        raise ValueError("convert_MR: Please specify a 'to' unit.")
    if from_ is None:
        raise ValueError("convert_MR: Please specify a 'from' unit.")

    P = stp_val(from_, "mr", S, t, P, P_chk=False, msg="convert_MR")
    P = stp_val(to, "mr", S, t, P, P_chk=True, msg="convert_MR")
    for name, v in (("S", S), ("t", t), ("P", P)):
        if v is not None and np.ndim(v) > 0 and np.size(v) != 1:
            raise ValueError(
                f"convert_MR: The '{name}' input should be a single value. "
                "Rates determined in different physical conditions should be analysed and converted separately.")

    from_sep = split_unit_string(from_)
    to_sep = split_unit_string(to)
    if len(from_sep) != len(to_sep):
        raise ValueError(
            "convert_MR: Parsing of 'from' and/or 'to' units has failed. Check unit_args() for accepted units "
            "and formatting. They should *both* be absolute, mass-specific, or area-specific rates and use "
            "same general formatting.")

    from_types = [unit_type_o1(from_sep[0], msg="convert_MR"), unit_type(from_sep[1], msg="convert_MR")]
    if len(from_sep) == 3:
        from_types.append(unit_type(from_sep[2], msg="convert_MR"))
    to_types = [unit_type_o1(to_sep[0], msg="convert_MR"), unit_type(to_sep[1], msg="convert_MR")]
    if len(to_sep) == 3:
        to_types.append(unit_type(to_sep[2], msg="convert_MR"))
    if from_types != to_types:
        raise ValueError(
            "convert_MR: 'from' and 'to' unit types conflict.\n"
            "Rate unit strings should be in correct order: O2/Time or O2/Time/Mass or O2/Time/Area.\n"
            "See unit_args() for details.")
    if len(from_types) == 2:
        rate_type = "abs"
    elif from_types[2] == "mass":
        rate_type = "mass.spec"
    elif from_types[2] == "area":
        rate_type = "area.spec"
    else:
        raise ValueError(f"convert_MR: unit '{from_sep[2]}' not recognised as a mass or area unit.")

    f1 = units_val(from_sep[0], "o1")
    f2 = units_val(from_sep[1], "time")
    t1 = units_val(to_sep[0], "o1")
    t2 = units_val(to_sep[1], "time")
    if rate_type == "mass.spec":
        f3 = units_val(from_sep[2], "mass")
        t3 = units_val(to_sep[2], "mass")
    elif rate_type == "area.spec":
        f3 = units_val(from_sep[2], "area")
        t3 = units_val(to_sep[2], "area")

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        rate_adj = adjust_scale(rate, f2, "hr.time")
        if rate_type == "mass.spec":
            rate_adj = adjust_scale(rate_adj, "kg.mass", f3)
        elif rate_type == "area.spec":
            rate_adj = adjust_scale_area(rate_adj, "m2.area", f3)
        ox_unit = units_val(f"{units_clean(f1, 'o1')}/l", "o2")
        rate_adj = convert_DO(rate_adj, ox_unit, "mg/l", S=S, t=t, P=P)
        out = convert_rate(rate_adj, oxy_unit="mg/l", time_unit="hour", output_unit=to,
                           volume=1, mass=1 if rate_type == "mass.spec" else None,
                           area=1 if rate_type == "area.spec" else None,
                           S=S, t=t, P=P, plot=False)
    rate_out_val = out.rate_output
    rate_out_un = out.output_unit

    if obj:
        # update the input object in place (mirrors respR)
        x.rate_output = np.asarray(rate_out_val)
        x.output_unit = rate_out_un
        x.summary["rate.output"] = np.asarray(rate_out_val)
        x.summary["output.unit"] = np.array([rate_out_un] * np.size(rate_out_val))
        x.summary["rate.abs"] = rate_out_val if rate_type == "abs" else x.summary.get("rate.abs")
        if rate_type == "mass.spec":
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                rates_abs = adjust_scale(np.asarray(x.summary["rate.abs"], dtype=float), f2, "hr.time")
                rates_abs = convert_DO(rates_abs, ox_unit, "mg/l", S=S, t=t, P=P)
                unit_abs = f"{to_sep[0]}/{to_sep[1]}"
                unit_abs = unit_abs.replace(".o2", "").replace(".time", "")
                rates_abs = convert_rate(rates_abs, oxy_unit="mg/l", time_unit="hour",
                                         output_unit=unit_abs, volume=1, S=S, t=t, P=P, plot=False).rate_output
            x.summary["rate.abs"] = np.asarray(rates_abs)
        x.call = None
        return x
    return rate_out_val
