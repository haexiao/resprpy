# ---------------------------------------------------------------------------
def convert_DO(x, from_=None, to=None, S=None, t=None, P=None, simplify=True):
    """Convert dissolved oxygen concentrations between units.

    Parameters
    ----------
    x : array-like
        Oxygen concentration values.
    from_, to : str
        Oxygen units, e.g. 'mg/L', 'umol/L', '%Air', 'kPa'. See unit_args().
    S, t, P : float, optional
        Salinity (psu), temperature (degC), atmospheric pressure (bar).
        Required only for units that depend on physical conditions
        (e.g. %Air, mg/kg, kPa).
    simplify : bool
        If True (default) return just the converted values; if False return
        the full result object.

    Returns
    -------
    Converted values (or a ConvertDO result object if simplify=False).
    """
    z = _asnum(x)
    fru = units_val(from_, "o2", msg="convert_DO")
    tou = units_val(to, "o2", msg="convert_DO")
    P = stp_val(fru, "oxy", S, t, P, P_chk=False, msg="convert_DO")
    P = stp_val(tou, "oxy", S, t, P, P_chk=True, msg="convert_DO")

    if S is not None and np.ndim(S) > 0 and np.size(S) != 1 and np.size(S) != np.size(z):
        raise ValueError("convert_DO: The 'S' input must be a single value or the same length as the rates to be converted.")
    if t is not None and np.ndim(t) > 0 and np.size(t) != 1 and np.size(t) != np.size(z):
        raise ValueError("convert_DO: The 't' input must be a single value or the same length as the rates to be converted.")
    if P is not None and np.ndim(P) > 0 and np.size(P) != 1 and np.size(P) != np.size(z):
        raise ValueError("convert_DO: The 'P' input must be a single value or the same length as the rates to be converted.")

    StPreq = stp_check(fru, "oxy") or stp_check(tou, "oxy")
    if StPreq:
        omVl = np.asarray(ml.molvol(t=t, P=P, species="O2"), dtype=float)
        oGas = np.asarray(ml.gas_satconc(S=S, t=t, P=P, species="O2"), dtype=float)
        swDn = np.asarray(ml.sw_dens(S=S, t=t, P=P), dtype=float)
        vpor = np.asarray(ml.vapor(S=S, t=t), dtype=float)
    omWt = ml.molweight("O2")
    oAtm = ml.ATM_COMP["O2"]

    # ---- input unit -> mg/L ----
    if fru == "mg/L.o2":
        c = z
    elif fru == "ug/L.o2":
        c = z / 1000
    elif fru == "mol/L.o2":
        c = z * omWt * 1000
    elif fru == "mmol/L.o2":
        c = z * omWt
    elif fru == "umol/L.o2":
        c = z * omWt / 1000
    elif fru == "nmol/L.o2":
        c = z * omWt / 1e6
    elif fru == "pmol/L.o2":
        c = z * omWt / 1e9
    elif fru == "mL/L.o2":
        c = z * omWt / omVl
    elif fru == "uL/L.o2":
        c = z * omWt / omVl / 1000
    elif fru == "cm3/L.o2":
        c = z * omWt / omVl
    elif fru == "mm3/L.o2":
        c = z * omWt / omVl / 1000
    elif fru == "mg/kg.o2":
        c = z * swDn / 1000
    elif fru == "ug/kg.o2":
        c = z * swDn / 1e6
    elif fru == "mol/kg.o2":
        c = z * swDn * omWt
    elif fru == "mmol/kg.o2":
        c = z * swDn * omWt / 1000
    elif fru == "umol/kg.o2":
        c = z * swDn * omWt / 1e6
    elif fru == "nmol/kg.o2":
        c = z * swDn * omWt / 1e9
    elif fru == "pmol/kg.o2":
        c = z * swDn * omWt / 1e12
    elif fru == "%Air.o2":
        c = z * oGas * omWt / 1000 / 100
    elif fru == "%Oxy.o2":
        c = z * oGas * omWt / oAtm / 1000 / 100
    elif fru == "mL/kg.o2":
        c = z * omWt / omVl * swDn / 1000
    elif fru == "uL/kg.o2":
        c = z * omWt / omVl * swDn / 1e6
    elif fru == "cm3/kg.o2":
        c = z * omWt / omVl * swDn / 1000
    elif fru == "mm3/kg.o2":
        c = z * omWt / omVl * swDn / 1e6
    elif fru == "Torr.o2p":
        c = z / (P - vpor) / oAtm * oGas * omWt / 1000 / 760.00006600500001
    elif fru == "hPa.o2p":
        c = z / (P - vpor) / oAtm * oGas * omWt / 1000 / 1013.235
    elif fru == "kPa.o2p":
        c = z / (P - vpor) / oAtm * oGas * omWt / 1000 / 101.3235
    elif fru == "mmHg.o2p":
        c = z / (P - vpor) / oAtm * oGas * omWt / 1000 / 759.99995199600005
    elif fru == "inHg.o2p":
        c = z / (P - vpor) / oAtm * oGas * omWt / 1000 / 29.9212583001
    else:
        raise ValueError(f"convert_DO: unit '{from_}' not handled.")

    # ---- mg/L -> output unit ----
    if tou == "mg/L.o2":
        out = c
    elif tou == "ug/L.o2":
        out = c * 1000
    elif tou == "mol/L.o2":
        out = c / omWt / 1000
    elif tou == "mmol/L.o2":
        out = c / omWt
    elif tou == "umol/L.o2":
        out = c / omWt * 1000
    elif tou == "nmol/L.o2":
        out = c / omWt * 1e6
    elif tou == "pmol/L.o2":
        out = c / omWt * 1e9
    elif tou == "mL/L.o2":
        out = c / omWt * omVl
    elif tou == "uL/L.o2":
        out = c / omWt * omVl * 1000
    elif tou == "cm3/L.o2":
        out = c / omWt * omVl
    elif tou == "mm3/L.o2":
        out = c / omWt * omVl * 1000
    elif tou == "mg/kg.o2":
        out = c / swDn * 1000
    elif tou == "ug/kg.o2":
        out = c / swDn * 1e6
    elif tou == "mol/kg.o2":
        out = c / omWt / swDn
    elif tou == "mmol/kg.o2":
        out = c / omWt / swDn * 1000
    elif tou == "umol/kg.o2":
        out = c / omWt / swDn * 1e6
    elif tou == "nmol/kg.o2":
        out = c / omWt / swDn * 1e9
    elif tou == "pmol/kg.o2":
        out = c / omWt / swDn * 1e12
    elif tou == "%Air.o2":
        out = c / omWt / oGas * 1000 * 100
    elif tou == "%Oxy.o2":
        out = c / omWt / oGas * oAtm * 1000 * 100
    elif tou == "mL/kg.o2":
        out = c / swDn * omVl / omWt * 1000
    elif tou == "uL/kg.o2":
        out = c / swDn * omVl / omWt * 1e6
    elif tou == "cm3/kg.o2":
        out = c / swDn * omVl / omWt * 1000
    elif tou == "mm3/kg.o2":
        out = c / swDn * omVl / omWt * 1e6
    elif tou == "Torr.o2p":
        out = c / omWt / oGas * oAtm * (P - vpor) * 1000 * 760.00006600500001
    elif tou == "hPa.o2p":
        out = c / omWt / oGas * oAtm * (P - vpor) * 1000 * 1013.253
    elif tou == "kPa.o2p":
        out = c / omWt / oGas * oAtm * (P - vpor) * 1000 * 101.3253
    elif tou == "mmHg.o2p":
        out = c / omWt / oGas * oAtm * (P - vpor) * 1000 * 759.99995199600005
    elif tou == "inHg.o2p":
        out = c / omWt / oGas * oAtm * (P - vpor) * 1000 * 29.9212583001
    else:
        raise ValueError(f"convert_DO: unit '{to}' not handled.")

    fru_clean = units_clean(fru, "o2")
    tou_clean = units_clean(tou, "o2")
    if simplify:
        return out
    return ConvertDO(call=None, input=z, output=out, input_unit=fru_clean,
                     output_unit=tou_clean)


@dataclass
class ConvertDO:
    call: object
    input: np.ndarray
    output: np.ndarray
    input_unit: str
    output_unit: str


