_PRESSURE_UNITS = ["kPa.p", "hPa.p", "Pa.p", "uBar.p", "mBar.p", "Bar.p", "atm.p", "Torr.p"]
_PRESSURE_MULT = [100.0, 1000.0, 100000.0, 1000000.0, 1000.0, 1.0, 0.98692, 750.06]


def convert_val(x, from_=None, to=None):
    """Convert values between simple units: volume, temperature, mass,
    area, or pressure. Mirrors respR::convert_val."""
    x = _asnum(x)
    if from_ is None:
        raise ValueError("convert_val: 'from' is required")
    fr_unit = unit_type(from_, msg="convert_val")
    if fr_unit not in ("vol", "temperature", "mass", "area", "pressure"):
        raise ValueError("convert_val: 'from' unit is not one of the accepted unit types.")
    if to is None:
        to = {"vol": "L", "temperature": "C", "mass": "kg", "area": "m2", "pressure": "bar"}[fr_unit]
    to_unit = unit_type(to, msg="convert_val")
    if to_unit not in ("vol", "temperature", "mass", "area", "pressure"):
        raise ValueError("convert_val: 'to' unit is not one of the accepted unit types.")
    if fr_unit != to_unit:
        raise ValueError("convert_val: 'from' and 'to' appear to be different unit types.")

    unit_fr = units_val(from_, fr_unit)
    unit_to = units_val(to, to_unit)

    if to_unit in ("vol", "mass"):
        out = adjust_scale(x, unit_fr, unit_to)
    elif to_unit == "area":
        out = adjust_scale_area(x, unit_fr, unit_to)
    elif to_unit == "pressure":
        mult_fr = _PRESSURE_MULT[_PRESSURE_UNITS.index(unit_fr)]
        mult_to = _PRESSURE_MULT[_PRESSURE_UNITS.index(unit_to)]
        out = x * (mult_to / mult_fr)
    else:  # temperature
        if unit_fr == "C.temp":
            if unit_to == "K.temp":
                out = x + 273.15
            elif unit_to == "F.temp":
                out = x * 9 / 5 + 32
            else:
                out = x
        elif unit_fr == "K.temp":
            if unit_to == "C.temp":
                out = x - 273.15
            elif unit_to == "F.temp":
                out = x * 9 / 5 - 459.67
            else:
                out = x
        else:  # F.temp
            if unit_to == "C.temp":
                out = (x - 32) * 5 / 9
            elif unit_to == "K.temp":
                out = (x + 459.67) * 5 / 9
            else:
                out = x
    return out


