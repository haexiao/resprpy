@dataclass
class ConvertRate:
    """Result of convert_rate(). Mirrors the respR 'convert_rate' object."""
    call: object = None
    inputs: dict = field(default_factory=dict)
    dataframe: object = None
    summary: dict = field(default_factory=dict)
    rate_input: np.ndarray = None
    output_unit: str = None
    rate_output: np.ndarray = None

    def __repr__(self):
        return (f"<resprpy.ConvertRate n={np.size(self.rate_output)} "
                f"output.unit={self.output_unit!r}>")


def _rate_object_parts(x):
    """Extract (rate, summary) from a calc_rate/auto_rate/adjust_rate-like
    object (dataclass or dict), or (x, None) for plain numeric input."""
    if hasattr(x, "rate") and hasattr(x, "summary"):
        return x.rate, x.summary
    if isinstance(x, dict) and "rate" in x and "summary" in x:
        return x["rate"], x["summary"]
    return None, None


def convert_rate(x, oxy_unit=None, time_unit=None, output_unit=None,
                 volume=None, mass=None, area=None, S=None, t=None, P=None,
                 plot=False, **kwargs):
    """Convert metabolic (oxygen uptake) rates between units.

    respR equivalent: convert_rate(x, oxy.unit=..., time.unit=...,
    output.unit=..., volume=..., mass=..., area=..., S=..., t=..., P=...).

    Parameters
    ----------
    x : array-like or calc_rate/auto_rate/adjust_rate result
        The rate(s) in the original units (oxygen per time).
    oxy_unit : str
        Oxygen concentration unit of the original data, e.g. 'mg/L'.
    time_unit : str
        Time unit of the original data, e.g. 'sec', 'min', 'hour'.
    output_unit : str
        Desired rate unit, e.g. 'mg/h', 'umol/min/g', 'mL/h/kg'.
    volume : float
        Chamber volume (L). Required.
    mass, area : float, optional
        Organism mass (kg) or surface area (m2) for specific rates.
    S, t, P : float, optional
        Salinity, temperature, pressure (bar) if the units require them.
    """
    if oxy_unit is None or isinstance(oxy_unit, (int, float)):
        raise ValueError("convert_rate: The 'oxy.unit' of the original data is required.")
    if time_unit is None or isinstance(time_unit, (int, float)):
        raise ValueError("convert_rate: The 'time.unit' of the original data is required.")
    if output_unit is None and mass is None and area is None:
        warnings.warn("convert_rate: The 'output.unit' is not provided. Applying default: 'mg/h'")
        output_unit = "mg/h"
    if output_unit is None and mass is not None and area is None:
        warnings.warn("convert_rate: The 'output.unit' is not provided. Applying default: 'mg/h/kg'")
        output_unit = "mg/h/kg"
    if output_unit is None and mass is None and area is not None:
        warnings.warn("convert_rate: The 'output.unit' is not provided. Applying default: 'mg/h/m2'")
        output_unit = "mg/h/m2"
    if volume is None or not isinstance(volume, (int, float, np.number)):
        raise ValueError("convert_rate: The 'volume' input is required.")
    if mass is not None and area is not None:
        raise ValueError("convert_rate: Cannot have inputs for both 'mass' and 'area'.")

    rate_obj, summ_in = _rate_object_parts(x)
    if rate_obj is None:
        rate = _asnum(x)
        n = np.size(rate)
        summary = {"rank": np.arange(1, n + 1), "rate": np.asarray(rate).ravel()}
    else:
        rate = _asnum(rate_obj)
        summary = dict(summ_in)

    oxy = units_val(oxy_unit, "o2")
    time = units_val(time_unit, "time")
    ou = split_unit_string(output_unit)
    is_spec = len(ou) == 3
    if is_spec:
        if mass is not None and area is None:
            is_mass_spec, is_area_spec = True, False
        elif area is not None and mass is None:
            is_mass_spec, is_area_spec = False, True
        else:
            raise ValueError("convert_rate: 'output.unit' requires a value for 'mass' or 'area'")
    else:
        is_mass_spec = is_area_spec = False

    A = units_val(ou[0], "o1")
    B = units_val(ou[1], "time")
    if is_spec:
        C = units_val(ou[2], "mass" if is_mass_spec else "area")
    if not is_mass_spec and isinstance(mass, (int, float, np.number)):
        raise ValueError("convert_rate: A 'mass' has been entered, but a mass-specific unit has not been specified in 'output.unit'.")
    if not is_area_spec and isinstance(area, (int, float, np.number)):
        raise ValueError("convert_rate: An 'area' has been entered, but an area-specific unit has not been specified in 'output.unit'.")

    oxy_clean = units_clean(oxy, "o2")
    time_clean = units_clean(time, "time")
    out_clean = [re.sub(r"\..*", "", u) for u in (A, B)]
    if is_spec:
        out_clean.append(re.sub(r"\..*", "", C))
    out_clean[0] = out_clean[0] + "O2"
    output_clean = "/".join(out_clean)

    P = stp_val(oxy_clean, "oxy", S, t, P, P_chk=False, msg="convert_rate")
    P = stp_val(output_clean, "mr", S, t, P, P_chk=True, msg="convert_rate")
    for name, v in (("S", S), ("t", t), ("P", P)):
        if v is not None and np.ndim(v) > 0 and np.size(v) != 1:
            raise ValueError(f"convert_rate: The '{name}' input should be a single value. "
                             "Rates determined in different physical conditions should be analysed and converted separately.")

    # oxygen amount: convert rate to the concentration unit matching A
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        if A in ("pmol.o2", "nmol.o2", "umol.o2", "mmol.o2", "mol.o2"):
            RO2 = convert_DO(rate, oxy, "mmol/L", S, t, P)
            RO2 = adjust_scale(RO2, "mmol.o2", A)
        elif A in ("mg.o2", "ug.o2"):
            RO2 = convert_DO(rate, oxy, "mg/L", S, t, P)
            RO2 = adjust_scale(RO2, "mg.o2", A)
        elif A in ("mL.o2", "uL.o2"):
            RO2 = convert_DO(rate, oxy, "mL/L", S, t, P)
            RO2 = adjust_scale(RO2, "mL.o2", A)
        elif A == "cm3.o2":
            RO2 = convert_DO(rate, oxy, "cm3/L", S, t, P)
        elif A == "mm3.o2":
            RO2 = convert_DO(rate, oxy, "cm3/L", S, t, P) * 1000
        else:
            raise ValueError(f"convert_rate: output oxygen unit '{ou[0]}' not handled.")

    RO2 = adjust_scale(RO2, time, B)
    VO2 = RO2 * volume
    if is_mass_spec:
        multm = adjust_scale(mass, "kg.mass", C)
        VO2_mass_spec = VO2 / multm
    if is_area_spec:
        multm = adjust_scale_area(area, "m2.area", C)
        VO2_area_spec = VO2 / multm

    n = np.size(rate)
    if is_mass_spec:
        rate_output = np.broadcast_to(VO2_mass_spec, (n,))
        extra = {"rate.abs": np.broadcast_to(VO2, (n,)),
                 "rate.m.spec": np.broadcast_to(VO2_mass_spec, (n,)),
                 "rate.a.spec": np.full(n, np.nan)}
    elif is_area_spec:
        rate_output = np.broadcast_to(VO2_area_spec, (n,))
        extra = {"rate.abs": np.broadcast_to(VO2, (n,)),
                 "rate.m.spec": np.full(n, np.nan),
                 "rate.a.spec": np.broadcast_to(VO2_area_spec, (n,))}
    else:
        rate_output = np.broadcast_to(VO2, (n,))
        extra = {"rate.abs": np.broadcast_to(VO2, (n,)),
                 "rate.m.spec": np.full(n, np.nan),
                 "rate.a.spec": np.full(n, np.nan)}

    summary.update({
        "rate.input": np.broadcast_to(rate, (n,)),
        "oxy.unit": np.array([oxy_clean] * n),
        "time.unit": np.array([time_clean] * n),
        "volume": np.full(n, volume),
        "mass": np.full(n, np.nan if mass is None else mass),
        "area": np.full(n, np.nan if area is None else area),
        "S": np.full(n, np.nan if S is None else S),
        "t": np.full(n, np.nan if t is None else t),
        "P": np.full(n, np.nan if P is None else P),
        "output.unit": np.array([output_clean] * n),
        "rate.output": rate_output,
        **extra,
    })

    inputs = dict(x=x, oxy_unit=oxy_clean, time_unit=time_clean, output_unit=output_clean,
                  volume=volume, mass=mass, area=area, S=S, t=t, P=P)
    # R: keep the input dataframe for object inputs (calc_rate/auto_rate/
    # adjust_rate...); numeric input -> NULL
    df_in = getattr(x, "dataframe", None)
    return ConvertRate(call=None, inputs=inputs, dataframe=df_in,
                       summary=summary,
                       rate_input=np.broadcast_to(rate, (n,)),
                       output_unit=output_clean, rate_output=rate_output)


